-- 14. CAMP STOCK (Populated consistently from delivered shipments)
-- ----------------------------------------------------------------------------
INSERT INTO camp_stock (camp_id, item_id, quantity_on_hand)
SELECT 
  s.camp_id,
  sl.item_id,
  SUM(sl.quantity_sent) AS quantity_on_hand
FROM shipment s
JOIN shipment_line sl ON s.shipment_id = sl.shipment_id
WHERE s.status = 'delivered'
GROUP BY s.camp_id, sl.item_id;

